export function measureBitmapText(text: string): number {
  return text.length * (BITMAP_FONT_WIDTH + BITMAP_FONT_SPACING) - BITMAP_FONT_SPACING;
}

export function drawBitmapText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  align: CanvasTextAlign = "left"
) {
  const width = measureBitmapText(text);
  let cursorX =
    align === "center" ? Math.round(x - width / 2) : align === "right" ? x - width : x;

  for (const char of text) {
    const glyph = GLYPHS[char] ?? GLYPHS[" "];
    glyph.forEach((row, rowIndex) => {
      [...row].forEach((pixel, colIndex) => {
        if (pixel === "1") {
          ctx.fillRect(cursorX + colIndex, y + rowIndex, 1, 1);
        }
      });
    });
    cursorX += BITMAP_FONT_WIDTH + BITMAP_FONT_SPACING;
  }
}
